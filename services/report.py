def get_score_color(score):

    if score >= 80:
        return GREEN

    if score >= 60:
        return ORANGE

    return RED


def get_score_label(score):

    if score >= 80:
        return "Good"

    if score >= 60:
        return "Needs Attention"

    return "High Risk"


def get_severity_colors(severity):

    severity = severity.upper()

    if severity == "CRITICAL":
        return RED, RED_LIGHT

    if severity == "HIGH":
        return ORANGE, ORANGE_LIGHT

    if severity == "MEDIUM":
        return YELLOW, YELLOW_LIGHT

    return BLUE, BLUE_LIGHT


def format_evidence(evidence):

    if not evidence:
        return [
            ["Information", "No evidence available"]
        ]

    rows = []

    for key, value in evidence.items():

        if value is None:
            value = "Not detected"

        elif isinstance(value, bool):
            value = "Yes" if value else "No"

        rows.append(
            [
                str(key).replace("_", " ").title(),
                str(value),
            ]
        )

    return rows


def get_comparison_items(comparison, key):
    """Safely get comparison items from nested or flat comparison data."""

    if not comparison:
        return []

    if isinstance(comparison, dict):

        findings_comparison = comparison.get(
            "findings_comparison"
        )

        if isinstance(findings_comparison, dict):

            return findings_comparison.get(
                key,
                []
            ) or []

        return comparison.get(
            key,
            []
        ) or []

    findings_comparison = getattr(
        comparison,
        "findings_comparison",
        None
    )

    if findings_comparison:

        return getattr(
            findings_comparison,
            key,
            []
        ) or []

    return getattr(
        comparison,
        key,
        []
    ) or []


