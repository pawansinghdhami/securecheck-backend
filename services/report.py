def draw_header_footer(canvas, doc):

    canvas.saveState()

    width, height = A4

    # Header
    canvas.setFillColor(NAVY)

    canvas.rect(
        0,
        height - 12 * mm,
        width,
        12 * mm,
        fill=1,
        stroke=0,
    )

    canvas.setFillColor(WHITE)

    canvas.setFont(
        "Helvetica-Bold",
        9,
    )

    canvas.drawString(
        18 * mm,
        height - 8 * mm,
        "SECURECHECK",
    )

    canvas.setFont(
        "Helvetica",
        8,
    )

    canvas.drawRightString(
        width - 18 * mm,
        height - 8 * mm,
        "Website Security Assessment",
    )

    # Footer line
    canvas.setStrokeColor(GRAY_300)

    canvas.line(
        18 * mm,
        12 * mm,
        width - 18 * mm,
        12 * mm,
    )

    canvas.setFillColor(GRAY_500)

    canvas.setFont(
        "Helvetica",
        7,
    )

    canvas.drawString(
        18 * mm,
        7 * mm,
        "Generated by SecureCheck",
    )

    canvas.drawRightString(
        width - 18 * mm,
        7 * mm,
        f"Page {doc.page}",
    )

    canvas.restoreState()


